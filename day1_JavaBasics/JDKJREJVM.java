package day1_JavaBasics;

/*
 * Program Name : JDKJREJVM
 * Description  : Difference between JDK, JRE and JVM
 */

public class JDKJREJVM {

    public static void main(String[] args) {

        System.out.println("JDK  = Java Development Kit");
        System.out.println("JRE  = Java Runtime Environment");
        System.out.println("JVM  = Java Virtual Machine");

        System.out.println();

        System.out.println("Relationship:");
        System.out.println("JDK → JRE → JVM");

        System.out.println();

        System.out.println("JDK : Used for Developing Java Programs");
        System.out.println("JRE : Used for Running Java Programs");
        System.out.println("JVM : Executes Bytecode");

    }

}
