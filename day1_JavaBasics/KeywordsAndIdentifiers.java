package day1_JavaBasics;
/*
 * Program Name : KeywordsAndIdentifiers
 * Description  : Java Keywords and Identifier Rules
 */

public class KeywordsAndIdentifiers {

    public static void main(String[] args) {

        int age = 21;
        double percentage = 85.50;
        String studentName = "Tanvi";

        System.out.println("Student Name : " + studentName);
        System.out.println("Age          : " + age);
        System.out.println("Percentage   : " + percentage);

        System.out.println();

        System.out.println("Examples of Java Keywords:");
        System.out.println("class");
        System.out.println("public");
        System.out.println("static");
        System.out.println("void");
        System.out.println("if");
        System.out.println("else");
        System.out.println("return");
        System.out.println("new");

    }

}